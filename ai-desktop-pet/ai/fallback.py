"""AI 未配置时的降级回复"""
import random

_RESPONSES = [
    "呜……我现在还没接入大脑（AI），你先去设置里填一下 API 配置吧~",
    "小笨蛋，主人还没给我配置 AI 模型呢，配置好了我就能陪你聊天啦 (´•ω•̥`)",
    "呼呼，我还不会说话，去「设置」里给我接上 AI 大脑吧！",
    "主人！我还只是个会动的像素团子，等接上 AI 我就能好好聊天啦~",
    "欸嘿，本宠物暂时处于离线模式，先去设置里给我连上大模型吧！",
]

_KEYWORD = {
    "你好": ["你好呀主人！(ﾉ◕ヮ◕)ﾉ*:･ﾟ✧", "嗨嗨！今天也要开心哦~"],
    "饿": ["我也觉得肚子空空的，快喂我吃点东西吧~", "呜……好想吃好吃的 (｡•́︿•̀｡)"],
    "累": ["主人辛苦啦，要不要摸摸我休息一下呀~", "困困……想打个盹儿了 Zzz"],
    "可爱": ["诶嘿，被主人夸了！好开心 (≧▽≦)", "嘿嘿，我可是主人最可爱的桌宠呢~"],
    "拜拜": ["拜拜主人，我会想你的！", "下次再来找我玩呀 (´▽`)"],
}


class FallbackResponder:
    """未配置 AI 时使用模板回复，保证基础体验。"""

    def respond(self, text: str) -> str:
        for key, replies in _KEYWORD.items():
            if key in text:
                return random.choice(replies)
        return random.choice(_RESPONSES)
